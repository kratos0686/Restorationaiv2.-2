import { 
  Project, 
  WaterCategory, 
  LossClass, 
  ProjectDocumentationTemplates, 
  ClientIntakeForm, 
  ProjectScopeOutline, 
  InitialDamageAssessmentChecklist,
  ScopeOutlineItem,
  DamageAssessmentChecklistItem
} from '../types';

/**
 * Automatically generates a standardized set of pre-filled documentation templates
 * for newly initiated water mitigation projects in accordance with IICRC S500 standards.
 */
export function generateDefaultProjectTemplates(
  projectInfo: Partial<Project> & { client?: string; address?: string; lossDate?: string }
): ProjectDocumentationTemplates {
  const now = new Date();
  const currentDateStr = now.toISOString().slice(0, 10);
  const currentTimeStr = now.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
  const autoGeneratedAt = now.toISOString();

  const clientName = projectInfo.client?.trim() || 'New Client';
  const propertyAddress = projectInfo.address?.trim() || 'Site Address TBD';
  const rawDate = projectInfo.lossDate || currentDateStr;
  const formattedLossDate = rawDate.includes('T') ? rawDate.slice(0, 10) : rawDate;
  
  const category = projectInfo.waterCategory || WaterCategory.CAT_1;
  const lossClass = projectInfo.lossClass || LossClass.CLASS_1;
  const insurance = projectInfo.insurance || '';
  const policyNumber = projectInfo.policyNumber || '';
  const claimNumber = projectInfo.claimNumber || '';
  const clientPhone = projectInfo.clientPhone || '';
  const clientEmail = projectInfo.clientEmail || '';
  const adjuster = projectInfo.adjuster || '';

  // Determine standard source text based on Water Category
  let defaultSourceDesc = 'Clean municipal supply line failure under pressure (no chemical or bio-contaminants).';
  if (category === WaterCategory.CAT_2) {
    defaultSourceDesc = 'Gray water overflow containing significant chemical or biological contamination (e.g. appliance discharge/sump pump).';
  } else if (category === WaterCategory.CAT_3) {
    defaultSourceDesc = 'Grossly contaminated black water / sewage backflow or rising exterior flood waters with pathogenic agents.';
  }

  // Determine estimated drying time & containment by category and class
  let estimatedDays = 3;
  let containmentLevel: ProjectScopeOutline['containmentLevel'] = 'None Required';
  let hepaRequired = false;
  let targetDryStd = 'Moisture content < 12% wood, < 16% drywall (relative to baseline dry standard)';
  let dehuCapacity = '70 - 100 AHAM PPD';
  let airMoversEst = 4;

  if (category === WaterCategory.CAT_3) {
    estimatedDays = 5;
    containmentLevel = 'Full Critical Barrier with Negative Air';
    hepaRequired = true;
    targetDryStd = 'Drywall removed (24" above flood line), framing < 15% WME, post-clearance microbial test passed';
  } else if (category === WaterCategory.CAT_2) {
    estimatedDays = 4;
    containmentLevel = 'Source Containment';
    hepaRequired = true;
  }

  if (lossClass === LossClass.CLASS_2) {
    airMoversEst = 6;
    dehuCapacity = '110 - 150 AHAM PPD';
    estimatedDays = Math.max(estimatedDays, 4);
  } else if (lossClass === LossClass.CLASS_3) {
    airMoversEst = 10;
    dehuCapacity = '150 - 220 AHAM PPD';
    estimatedDays = Math.max(estimatedDays, 5);
  } else if (lossClass === LossClass.CLASS_4) {
    airMoversEst = 8;
    dehuCapacity = 'Desiccant Dehumidifier or High-Temperature LGR with Specialty Cavity Drying Systems';
    estimatedDays = Math.max(estimatedDays, 7);
    targetDryStd = 'Deep bound moisture stabilization (hardwood / plaster / dense subflooring)';
  }

  // 1. Client Intake Form Template (Pre-filled)
  const clientIntake: ClientIntakeForm = {
    id: `intake-${Date.now()}`,
    templateType: 'client_intake',
    title: 'Client Intake & Work Authorization',
    createdAt: autoGeneratedAt,
    updatedAt: autoGeneratedAt,
    status: 'draft',
    clientName,
    clientPhone,
    clientEmail,
    propertyAddress,
    lossDate: formattedLossDate,
    intakeDate: currentDateStr,
    insuranceCarrier: insurance,
    policyNumber,
    claimNumber,
    adjusterName: adjuster,
    adjusterPhone: projectInfo.adjusterPhone || '',
    adjusterEmail: projectInfo.adjusterEmail || '',
    waterCategory: category,
    lossClass,
    waterSourceDescription: defaultSourceDesc,
    emergencyContactName: '',
    emergencyContactPhone: '',
    occupancyStatus: 'Owner Occupied',
    propertyType: 'Single Family',
    yearBuilt: '1998',
    pre1985Structure: false,
    waterTurnedOff: true,
    powerStatus: 'Active',
    specialAccessInstructions: 'Technicians on site during standard business hours; client request 30-min call ahead.',
    technicianNotes: `Initial project intake pre-populated on ${currentDateStr} at ${currentTimeStr}. Category: ${category}, Class: ${lossClass}.`,
    workAuthorizationSigned: false,
    signedByName: clientName
  };

  // 2. Project Scope Outline Template (Pre-filled & IICRC S500 Structured)
  const scopeItems: ScopeOutlineItem[] = [
    {
      id: 'sc-1',
      category: 'Containment & Protection',
      task: 'Job Site Safety Isolation & Surface Protection',
      description: category === WaterCategory.CAT_3 
        ? 'Erect 6-mil poly critical containment barriers with zippered airlocks. Maintain negative air pressure (minimum 4 ACH).'
        : 'Install adhesive poly carpet runners and neoprene floor protection along high-traffic ingress/egress corridors.',
      standardReference: 'IICRC S500 Sec 10.4',
      status: 'pending',
      estimatedQuantity: category === WaterCategory.CAT_3 ? '2 Airlocks + Poly Barrier' : '150 sq ft protection'
    },
    {
      id: 'sc-2',
      category: 'Water Extraction',
      task: 'Bulk Standing Water Physical Extraction',
      description: 'Perform deep-vacuum surface extraction on all affected hard flooring and saturated sub-surfaces to remove free water.',
      standardReference: 'IICRC S500 Sec 12.2',
      status: 'pending',
      estimatedQuantity: 'Weighted drag extraction tool & rover wand'
    },
    {
      id: 'sc-3',
      category: 'Controlled Demolition',
      task: category === WaterCategory.CAT_3 
        ? 'Removal of Porous Materials (Carpet, Pad, Drywall Flood Cut 24" Above Wet Line)'
        : 'Removal of Non-Salvageable Wet Materials & Baseboard Detachment',
      description: category === WaterCategory.CAT_3
        ? 'Remove and bag all Category 3 contaminated porous items including carpet padding, contaminated drywall 24" above waterline, and saturated insulation.'
        : 'Carefully detach baseboards and perforate lower drywall cavities to facilitate cross-cavity drying airflow without unnecessary structural demo.',
      standardReference: 'IICRC S500 Sec 12.3 / ANSI S520',
      status: 'pending',
      estimatedQuantity: category === WaterCategory.CAT_3 ? 'Perimeter flood cuts (24")' : 'Baseboard removal & vent holes'
    },
    {
      id: 'sc-4',
      category: 'Antimicrobial & Cleaning',
      task: 'EPA-Registered Botanical Antimicrobial Treatment',
      description: category === WaterCategory.CAT_3
        ? 'Perform complete detergent wash followed by hospital-grade EPA disinfectant application on exposed framing, sills, and subfloors.'
        : 'Apply botanical antimicrobial bio-inhibitor mist across all exposed structural framing to suppress microbial germination.',
      standardReference: 'IICRC S500 Sec 10.6',
      status: 'pending',
      estimatedQuantity: 'Low-pressure ULV cold fogging / direct spray'
    },
    {
      id: 'sc-5',
      category: 'Drying Equipment',
      task: 'Deploy Psychrometric Evaporation & Dehumidification System',
      description: `Install ${airMoversEst} high-velocity axial air movers angled at 45° across wet perimeters. Place ${dehuCapacity} LGR dehumidifier for vapor pressure reduction.`,
      standardReference: 'IICRC S500 Sec 13.5',
      status: 'pending',
      estimatedQuantity: `${airMoversEst} Air Movers + 1 LGR Dehumidifier (${dehuCapacity})`
    },
    {
      id: 'sc-6',
      category: 'Monitoring & Verification',
      task: 'Daily Psychrometric & Material Moisture Tracking',
      description: 'Record daily ambient Temp, RH, Dew Point, GPP (Grains Per Pound), and pin/pinless moisture meter readings on drywall, trim, and subflooring until dry standard is achieved.',
      standardReference: 'IICRC S500 Sec 14.1',
      status: 'pending',
      estimatedQuantity: 'Daily monitoring logs (Est. 3-5 days)'
    }
  ];

  if (hepaRequired) {
    scopeItems.splice(4, 0, {
      id: 'sc-hepa',
      category: 'Containment & Protection',
      task: 'HEPA 500 Air Filtration Device (AFD) Continuous Scrubbing',
      description: 'Run HEPA 500 air scrubber continuously to capture airborne particulate, mold spores, and bio-aerosols throughout demolition and drying.',
      standardReference: 'IICRC S520 / EPA Mold Remediation',
      status: 'pending',
      estimatedQuantity: '1x 500 CFM HEPA Unit'
    });
  }

  const scopeOutline: ProjectScopeOutline = {
    id: `scope-${Date.now()}`,
    templateType: 'scope_outline',
    title: 'IICRC S500 Water Mitigation Scope Outline',
    createdAt: autoGeneratedAt,
    updatedAt: autoGeneratedAt,
    status: 'draft',
    clientName,
    propertyAddress,
    date: formattedLossDate,
    waterCategory: category,
    lossClass,
    targetDryStandard: targetDryStd,
    estimatedDryingDurationDays: estimatedDays,
    containmentLevel,
    dehumidifierCapacityTarget: dehuCapacity,
    airMoverCountEstimated: airMoversEst,
    hepaAirScrubberRequired: hepaRequired,
    scopeItems
  };

  // 3. Initial Damage Assessment Checklist Template (Pre-filled)
  const checklistItems: DamageAssessmentChecklistItem[] = [
    {
      id: 'chk-1',
      section: 'Source & Containment',
      item: 'Water Supply Source Valve Shut Off',
      description: 'Verify that the primary water intrusion source or shut-off valve is closed and static pressure has dropped.',
      status: 'pass',
      severity: 'critical',
      notes: 'Main supply isolated. No active pressurized leak currently observed.'
    },
    {
      id: 'chk-2',
      section: 'Health, Life & Safety',
      item: 'Electrical Circuit Isolation & Hazard Clearance',
      description: 'Inspect electrical panel, outlets, and switches in affected wet zones; de-energize circuits in standing water areas.',
      status: 'pass',
      severity: 'critical',
      notes: 'No outlets submerged; technicians inspected panel and locked out affected circuits.'
    },
    {
      id: 'chk-3',
      section: 'Health, Life & Safety',
      item: 'Overhead Ceiling Collapse / Sagging Drywall Inspection',
      description: 'Check upper ceilings for water retention, belly bulges, or drywall joint separation that poses falling hazard.',
      status: 'pass',
      severity: 'moderate',
      notes: 'Ceiling checked with thermal imaging camera; no hidden water pockets found overhead.'
    },
    {
      id: 'chk-4',
      section: 'Building Assemblies & Moisture',
      item: 'Perimeter Drywall Wicking Height Mapping',
      description: 'Measure wicking moisture height on all perimeter walls using non-invasive and penetrating moisture meters.',
      status: 'action_required',
      severity: 'moderate',
      notes: 'Moisture readings elevated up to 16-24 inches above finished floor; baseboards require release.'
    },
    {
      id: 'chk-5',
      section: 'Building Assemblies & Moisture',
      item: 'Flooring System & Subfloor Saturation Audit',
      description: 'Inspect flooring materials (hardwood, vinyl plank, carpet, tile) and subfloor (plywood, OSB, concrete slab).',
      status: 'action_required',
      severity: 'moderate',
      notes: 'Elevated moisture detected under floor coverings; perimeter test holes indicate concrete slab surface moisture.'
    },
    {
      id: 'chk-6',
      section: 'HVAC & Airflow',
      item: 'HVAC System Isolation & Return Air Grille Sealing',
      description: 'Turn off or isolate central HVAC systems in contaminated rooms to prevent circulating aerosolized contaminants.',
      status: category === WaterCategory.CAT_1 ? 'pass' : 'action_required',
      severity: 'moderate',
      notes: category === WaterCategory.CAT_1 
        ? 'HVAC running for dehumidification support with fresh filters in place.' 
        : 'HVAC return grilles sealed with plastic sheeting to isolate work area.'
    },
    {
      id: 'chk-7',
      section: 'Contents & Valuables',
      item: 'Furniture Block & Pad Protection',
      description: 'Raise all wood and metal furniture legs onto Styrofoam blocks or plastic moisture tabs to halt wicking and rust stains.',
      status: 'action_required',
      severity: 'normal',
      notes: 'Technician team equipped with blocks/tabs to stage contents.'
    },
    {
      id: 'chk-8',
      section: 'Environmental & Regulatory',
      item: 'Pre-1985 Asbestos / Lead Containing Materials Threshold',
      description: 'Determine building construction year; if built prior to 1985, mandate testing before destructive demo of drywall/flooring.',
      status: 'pass',
      severity: 'critical',
      notes: 'Structure verified post-1985 construction. Standard mitigation demolition protocols permitted.'
    },
    {
      id: 'chk-9',
      section: 'Environmental & Regulatory',
      item: 'Microbial Odor & Visible Mold Inspection',
      description: 'Conduct visual and olfactory assessment for preexisting mold colonies or musty odors in concealed wall spaces.',
      status: category === WaterCategory.CAT_3 ? 'action_required' : 'pass',
      severity: category === WaterCategory.CAT_3 ? 'critical' : 'normal',
      notes: category === WaterCategory.CAT_3 
        ? 'Sewage odor detected; requires immediate bio-wash and continuous HEPA filtration.'
        : 'No preexisting visible mold colonies observed on accessible drywall surfaces.'
    }
  ];

  const damageAssessment: InitialDamageAssessmentChecklist = {
    id: `assess-${Date.now()}`,
    templateType: 'damage_assessment',
    title: 'Initial Water Damage Assessment Checklist',
    createdAt: autoGeneratedAt,
    updatedAt: autoGeneratedAt,
    status: 'draft',
    clientName,
    propertyAddress,
    assessmentDate: formattedLossDate,
    inspectorName: 'Lead Mitigation Technician',
    waterCategory: category,
    lossClass,
    overallConditionRating: category === WaterCategory.CAT_3 || lossClass === LossClass.CLASS_3 ? 'Moderate' : 'Minor',
    sourceIdentified: true,
    sourceDescription: defaultSourceDesc,
    standingWaterDepthInches: 0.5,
    visibleMicrobialGrowth: category === WaterCategory.CAT_3,
    microbialDescription: category === WaterCategory.CAT_3 ? 'Suspected microbial contamination due to sewage / black water intrusion' : undefined,
    structuralIntegrityCompromised: false,
    electricalHazardsPresent: false,
    checklistItems,
    summaryConclusion: `Initial damage inspection complete for ${clientName} at ${propertyAddress}. Classified as ${category}, ${lossClass}. Containment protocol: ${containmentLevel}. Immediate extraction and controlled moisture evaporation recommended.`,
    recommendations: [
      'Perform high-efficiency deep water extraction immediately to reduce boundary layer vapor.',
      'Deploy industrial LGR dehumidifier and directed axial air movers as per IICRC S500 formulas.',
      'Detach baseboards to inspect gypsum core saturation and establish wall cavity drying ports.',
      'Conduct daily psychrometric readings (Temp, RH, Dew Point, GPP) at the same time each morning.'
    ]
  };

  return {
    autoGeneratedAt,
    clientIntake,
    scopeOutline,
    damageAssessment
  };
}

/**
 * Validates and ensures that a project object has its documentationTemplates populated.
 * If missing, generates them on-the-fly and pre-fills all known fields.
 */
export function ensureProjectDocumentationTemplates(project: Project): Project {
  if (
    project.documentationTemplates &&
    project.documentationTemplates.clientIntake &&
    project.documentationTemplates.scopeOutline &&
    project.documentationTemplates.damageAssessment
  ) {
    return project;
  }

  const generated = generateDefaultProjectTemplates(project);
  return {
    ...project,
    documentationTemplates: generated
  };
}
